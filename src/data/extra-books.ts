import type { Book } from "./sample-book";

function make(
  id: string,
  title: string,
  author: string,
  chapters: { title: string; paragraphs: string[] }[],
): Book {
  return {
    id,
    title,
    author,
    chapters: chapters.map((chapter, chapterIndex) => {
      const chapterId = `${id}-ch${chapterIndex + 1}`;
      return {
        id: chapterId,
        title: chapter.title,
        paragraphs: chapter.paragraphs.map((text, index) => ({
          id: `${chapterId}-p${index}`,
          text,
        })),
      };
    }),
  };
}


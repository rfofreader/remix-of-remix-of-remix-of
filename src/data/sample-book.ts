export function bookText(book: Book): string {
  return book.chapters
    .flatMap((ch) => ch.paragraphs.map((p) => p.text))
    .join(" ");
}

export function totalChars(book: Book): number {
  return book.chapters.reduce(
    (sum, ch) => sum + ch.paragraphs.reduce((s, p) => s + p.text.length, 0),
    0,
  );
}

export interface BookParagraph {
  id: string;
  text: string;
}

export interface BookChapter {
  id: string;
  title: string;
  paragraphs: BookParagraph[];
}

export interface Book {
  id: string;
  title: string;
  author: string;
  chapters: BookChapter[];
}

function chapter(id: string, title: string, texts: string[]): BookChapter {
  return {
    id,
    title,
    paragraphs: texts.map((text, index) => ({ id: `${id}-p${index}`, text })),
  };
}

